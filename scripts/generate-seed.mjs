// Builds supabase/seed.sql from the mock data in src/data, so the database
// starts with exactly what the app shows in demo mode.
//   npm run db:seed-sql
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';

const root = fileURLToPath(new URL('..', import.meta.url));
// Vite loads the data files so their image imports resolve
const vite = await createServer({ root, logLevel: 'error', server: { middlewareMode: true }, appType: 'custom' });

try {
  const { hobbies } = await vite.ssrLoadModule('/src/data/hobbies.js');
  const { communities } = await vite.ssrLoadModule('/src/data/communities.js');
  const { posts } = await vite.ssrLoadModule('/src/data/posts.js');
  const { events } = await vite.ssrLoadModule('/src/data/events.js');
  const { users } = await vite.ssrLoadModule('/src/data/users.js');

  const str = v => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
  const num = v => (v == null ? '0' : String(Number(v)));
  const bool = v => (v ? 'true' : 'false');
  const arr = v => (v?.length ? `array[${v.map(str).join(', ')}]` : "'{}'");
  const rows = list => list.map(cols => `  (${cols.join(', ')})`).join(',\n');

  const authorName = id => users.find(u => u.id === id)?.name;

  const sql = `-- Generated by scripts/generate-seed.mjs from src/data — don't edit by hand.
-- Safe to re-run: catalogue rows are upserted, sample posts are skipped if present.

insert into public.hobbies (id, name, emoji, color, category, description, long_description, member_count, sort_order) values
${rows(hobbies.map((h, i) => [str(h.id), str(h.name), str(h.emoji), str(h.color), str(h.category), str(h.description), str(h.longDescription), num(h.memberCount), num(i)]))}
on conflict (id) do update set
  name = excluded.name, emoji = excluded.emoji, color = excluded.color, category = excluded.category,
  description = excluded.description, long_description = excluded.long_description, sort_order = excluded.sort_order;

insert into public.communities (id, hobby_id, name, description, member_count, post_count, color, trending, tags, related_hobbies, sort_order) values
${rows(communities.map((c, i) => [str(c.id), str(c.hobbyId), str(c.name), str(c.description), num(c.memberCount), num(c.postCount), str(c.color), bool(c.trending), arr(c.tags), arr(c.relatedHobbies), num(i)]))}
on conflict (id) do update set
  hobby_id = excluded.hobby_id, name = excluded.name, description = excluded.description, color = excluded.color,
  trending = excluded.trending, tags = excluded.tags, related_hobbies = excluded.related_hobbies, sort_order = excluded.sort_order;

insert into public.events (id, title, category, date_label, time_label, location_type, location, description, interested_count, image_key, sort_order) values
${rows(events.map((e, i) => [str(e.id), str(e.title), str(e.category), str(e.date), str(e.time), str(e.locationType), str(e.location), str(e.description), num(e.interested), str(e.imageKey), num(i)]))}
on conflict (id) do update set
  title = excluded.title, category = excluded.category, date_label = excluded.date_label, time_label = excluded.time_label,
  location_type = excluded.location_type, location = excluded.location, description = excluded.description,
  image_key = excluded.image_key, sort_order = excluded.sort_order;

insert into public.posts (id, community_id, demo_author_id, author_name, type, title, body, interests, tags, reply_count, like_count, created_at) values
${rows(posts.map(p => [str(p.id), str(p.communityId), str(p.authorId), str(authorName(p.authorId)), str(p.type), str(p.title), str(p.body), arr(p.interests), arr(p.tags), num(p.replyCount), num(p.likeCount), str(p.createdAt)]))}
on conflict (id) do nothing;
`;

  const out = new URL('../supabase/seed.sql', import.meta.url);
  writeFileSync(out, sql);
  console.log(`Wrote ${fileURLToPath(out)}: ${hobbies.length} hobbies, ${communities.length} communities, ${events.length} events, ${posts.length} posts`);
} finally {
  await vite.close();
}
